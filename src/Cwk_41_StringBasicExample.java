public class Cwk_41_StringBasicExample {
        public static void main(String[] args) {
            String s = "Kunal";

            // 1. Length nikalna
            System.out.println("Length: " + s.length()); // Output: 5

            // 2. Character extract karna
            System.out.println("Char at index 2: " + s.charAt(2)); // Output: n

            // 3. Lowercase aur Uppercase
            System.out.println("Lowercase: " + s.toLowerCase()); // Output: kunal
            System.out.println("Uppercase: " + s.toUpperCase()); // Output: KUNAL
        }

}
